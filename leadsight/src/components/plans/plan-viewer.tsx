"use client";

import { useState } from "react";
import type { MarketingPlan, PlanItem, PlanSection } from "@/types/plan";

interface PlanViewerProps {
  plan: MarketingPlan;
  onExportDocs?: () => void;
  onRegenerate?: () => void;
}

const PRIORITY_COLORS: Record<string, string> = {
  high: "bg-red-100 text-red-700 border-red-200",
  medium: "bg-yellow-100 text-yellow-700 border-yellow-200",
  low: "bg-gray-100 text-gray-600 border-gray-200",
};

const EFFORT_COLORS: Record<string, string> = {
  quick_win: "bg-green-100 text-green-700",
  medium: "bg-blue-100 text-blue-700",
  strategic: "bg-purple-100 text-purple-700",
};

const EFFORT_LABELS: Record<string, string> = {
  quick_win: "Quick Win",
  medium: "Medium-term",
  strategic: "Strategic",
};

function PlanItemCard({ item }: { item: PlanItem }) {
  return (
    <div className="rounded-lg border border-gray-100 bg-gray-50 p-4 space-y-2">
      <div className="flex flex-wrap items-start justify-between gap-2">
        <h4 className="font-medium text-gray-900 text-sm">{item.title}</h4>
        <div className="flex gap-1.5">
          <span className={`rounded-full border px-2 py-0.5 text-xs font-medium ${PRIORITY_COLORS[item.priority]}`}>
            {item.priority}
          </span>
          <span className={`rounded-full px-2 py-0.5 text-xs font-medium ${EFFORT_COLORS[item.effort]}`}>
            {EFFORT_LABELS[item.effort]}
          </span>
        </div>
      </div>
      <p className="text-sm text-gray-600">{item.description}</p>
      <p className="text-xs text-gray-400 italic">{item.estimated_impact}</p>
    </div>
  );
}

function SectionTab({ section }: { section: PlanSection }) {
  return (
    <div className="space-y-3">
      <p className="text-sm text-gray-600">{section.summary}</p>
      {section.items.map((item, i) => <PlanItemCard key={i} item={item} />)}
    </div>
  );
}

const TABS = ["Overview", "Website", "Social", "Advertising", "Quick Wins", "Email"];

export function PlanViewer({ plan, onExportDocs, onRegenerate }: PlanViewerProps) {
  const [activeTab, setActiveTab] = useState("Overview");
  const [copied, setCopied] = useState(false);

  async function copyEmail() {
    await navigator.clipboard.writeText(plan.outreach_email_draft);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  }

  return (
    <div className="space-y-6">
      {/* Actions */}
      <div className="flex flex-wrap gap-2">
        {onExportDocs && (
          <button onClick={onExportDocs}
            className="rounded-lg border border-gray-300 bg-white px-4 py-2 text-sm font-medium text-gray-700 hover:bg-gray-50">
            Export to Google Docs
          </button>
        )}
        {onRegenerate && (
          <button onClick={onRegenerate}
            className="rounded-lg border border-gray-300 bg-white px-4 py-2 text-sm font-medium text-gray-700 hover:bg-gray-50">
            Regenerate Plan
          </button>
        )}
        <span className="ml-auto text-xs text-gray-400 self-center">
          Generated by {plan.model_used} · {new Date(plan.generated_at).toLocaleDateString()}
        </span>
      </div>

      {/* Tabs */}
      <div className="border-b border-gray-200">
        <nav className="flex gap-4 overflow-x-auto">
          {TABS.map(tab => (
            <button key={tab} onClick={() => setActiveTab(tab)}
              className={`whitespace-nowrap pb-3 text-sm font-medium border-b-2 transition-colors ${
                activeTab === tab
                  ? "border-blue-600 text-blue-600"
                  : "border-transparent text-gray-500 hover:text-gray-700"
              }`}>
              {tab}
            </button>
          ))}
        </nav>
      </div>

      {/* Tab content */}
      <div>
        {activeTab === "Overview" && (
          <div className="space-y-4">
            <div className="prose prose-sm max-w-none">
              {plan.executive_summary.split("\n\n").map((para, i) => (
                <p key={i} className="text-gray-700">{para}</p>
              ))}
            </div>
            {plan.quick_wins.length > 0 && (
              <div className="rounded-xl bg-green-50 border border-green-200 p-4 space-y-3">
                <h3 className="font-semibold text-green-800">⚡ Quick Wins ({plan.quick_wins.length})</h3>
                {plan.quick_wins.map((item, i) => <PlanItemCard key={i} item={item} />)}
              </div>
            )}
          </div>
        )}
        {activeTab === "Website" && <SectionTab section={plan.website_recommendations} />}
        {activeTab === "Social" && <SectionTab section={plan.social_recommendations} />}
        {activeTab === "Advertising" && <SectionTab section={plan.advertising_recommendations} />}
        {activeTab === "Quick Wins" && (
          <div className="space-y-3">
            {plan.quick_wins.map((item, i) => <PlanItemCard key={i} item={item} />)}
            <h3 className="font-semibold text-gray-700 pt-2">Medium-term Actions</h3>
            {plan.medium_term.map((item, i) => <PlanItemCard key={i} item={item} />)}
            <h3 className="font-semibold text-gray-700 pt-2">Long-term Strategy</h3>
            {plan.long_term.map((item, i) => <PlanItemCard key={i} item={item} />)}
          </div>
        )}
        {activeTab === "Email" && (
          <div className="space-y-3">
            <div className="flex items-center justify-between">
              <p className="text-sm text-gray-500">Ready-to-send outreach email</p>
              <button onClick={copyEmail}
                className="rounded-lg border border-gray-300 px-3 py-1.5 text-xs font-medium text-gray-700 hover:bg-gray-50">
                {copied ? "Copied!" : "Copy to Clipboard"}
              </button>
            </div>
            <textarea
              readOnly
              value={plan.outreach_email_draft}
              rows={16}
              className="w-full rounded-lg border border-gray-200 p-4 text-sm text-gray-700 font-mono bg-gray-50 resize-none focus:outline-none"
            />
          </div>
        )}
      </div>
    </div>
  );
}
